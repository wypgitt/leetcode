class Solution {
public:
    bool isValid(string s) {
        if (s.size() % 3) return false;
        vector<char> st;
        for (char ch : s) {
            st.push_back(ch);
            while (st.size() >= 3 && st[st.size() - 3] == 'a' && st[st.size() - 2] == 'b' && st.back() == 'c') {
                st.pop_back();
                st.pop_back();
                st.pop_back();
            }
        }
        return st.empty();
    }
};
